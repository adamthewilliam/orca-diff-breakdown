// Dev-only: copies Catppuccin's file icons into src/icons/. Re-run after changing the pins below:
//   bun scripts/vendor-icons.ts
// It clones both repos at their pinned tags into a temporary folder, checks each tag still points at
// the pinned commit, and only reads files from them (nothing from the clones is run).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

type Source = { repo: string; tag: string; commit: string }

const ICONS: Source = {
  repo: 'https://github.com/catppuccin/vscode-icons',
  tag: 'v1.26.0',
  commit: 'b6915da9f6889b683a110aa747de96c2820a537d'
}
const PALETTE: Source = {
  repo: 'https://github.com/catppuccin/palette',
  tag: 'v1.8.0',
  commit: '07d02aa110ef9eb7e7427afca5c73ba9cf7f8ebd'
}
const ROOT = join(import.meta.dirname, '..')
const OUT = join(ROOT, 'src', 'icons')
/** The plain file icon, used when nothing else matches. */
const FALLBACK = '_file'

type Association = { languageIds?: string[]; fileExtensions?: string[]; fileNames?: string[] }
type Palette = Record<'latte' | 'mocha', { colors: Record<string, { hex: string }> }>

function checkout(source: Source, dir: string): string {
  execFileSync(
    'git',
    [
      '-c',
      'advice.detachedHead=false',
      'clone',
      '--quiet',
      '--depth',
      '1',
      '--branch',
      source.tag,
      source.repo,
      dir
    ],
    {
      stdio: ['ignore', 'ignore', 'inherit']
    }
  )
  const head = execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
  if (head !== source.commit) throw new Error(`${source.repo} ${source.tag} is ${head}, not ${source.commit}`)
  return dir
}

/**
 * Reads the `fileIcons` object literal from upstream's src/defaults/fileIcons.ts as JSON (it is
 * plain data: quoted strings, arrays and keys), without running the file.
 */
function parseFileIcons(source: string): Record<string, Association> {
  const start = source.indexOf('{', source.indexOf('const fileIcons: FileIcons ='))
  const end = source.indexOf('\n}\n', start) + 2
  const json = source
    .slice(start, end)
    .replace(/'/g, '"')
    .replace(/^(\s*)(\w+):/gm, '$1"$2":')
    .replace(/,(\s*[}\]])/g, '$1')
  return JSON.parse(json) as Record<string, Association>
}

/** An icon's markup inside its <svg>, minified, with its ids made unique across the sprite. */
function iconBody(name: string, svg: string): string {
  return svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .replace(/\s*\/>/g, '/>')
    .trim()
    .replace(/var\(--vscode-ctp-/g, 'var(--ctp-')
    .replace(/\bid="([^"]+)"/g, `id="ci-${name}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#ci-${name}-$1)`)
}

function header(sources: Source[]): string {
  const from = sources.map((s) => `${s.repo} ${s.tag} @ ${s.commit}`).join('\n//   and ')
  return `// Generated by scripts/vendor-icons.ts from\n//   ${from}\n// (MIT, see THIRD_PARTY_NOTICES.md); do not edit.\n`
}

const literal = (value: unknown) => JSON.stringify(value, null, 2)

const work = mkdtempSync(join(tmpdir(), 'vendor-icons-'))
try {
  const icons = checkout(ICONS, join(work, 'vscode-icons'))
  const palette = checkout(PALETTE, join(work, 'palette'))
  const svgDir = join(icons, 'icons', 'css-variables')
  const svgPath = (name: string) => join(svgDir, `${name}.svg`)

  const associations = parseFileIcons(readFileSync(join(icons, 'src', 'defaults', 'fileIcons.ts'), 'utf8'))
  // Later entries win, as in upstream's own reduce over the same object.
  const fileNames: Record<string, string> = {}
  const fileExtensions: Record<string, string> = {}
  const missing = new Set<string>()
  // Icons matched only by VS Code language id: there is no language id here, so they never show.
  const languageOnly: string[] = []
  for (const [icon, { fileNames: names = [], fileExtensions: extensions = [] }] of Object.entries(
    associations
  )) {
    if (names.length + extensions.length === 0) {
      languageOnly.push(icon)
      continue
    }
    if (!existsSync(svgPath(icon))) {
      missing.add(icon)
      continue
    }
    for (const name of names) fileNames[name.toLowerCase()] = icon
    for (const extension of extensions) fileExtensions[extension.toLowerCase()] = icon
  }

  const used = [...new Set([FALLBACK, ...Object.values(fileNames), ...Object.values(fileExtensions)])].sort()
  const bodies: Record<string, string> = {}
  const viewBoxes: Record<string, string> = {}
  for (const name of used) {
    const svg = readFileSync(svgPath(name), 'utf8')
    const viewBox = svg.match(/<svg[^>]*\bviewBox="([^"]+)"/)?.[1]
    if (!viewBox) throw new Error(`${name}.svg has no viewBox`)
    if (viewBox !== '0 0 16 16') viewBoxes[name] = viewBox
    bodies[name] = iconBody(name, svg)
  }

  const colors = [
    ...new Set(Object.values(bodies).flatMap((b) => [...b.matchAll(/--ctp-(\w+)/g)].map((m) => m[1])))
  ]
  colors.sort()
  const flavours = JSON.parse(readFileSync(join(palette, 'palette.json'), 'utf8')) as Palette
  const pick = (flavour: 'latte' | 'mocha') =>
    Object.fromEntries(
      colors.map((c) => {
        const hex = flavours[flavour].colors[c]?.hex
        if (!hex) throw new Error(`palette has no ${flavour} ${c}`)
        return [c, hex]
      })
    )

  writeFileSync(
    join(OUT, 'svgs.ts'),
    header([ICONS]) +
      `\n/** Each file icon's markup inside its <svg>; colours are \`var(--ctp-<name>)\`. */\n` +
      `export const ICON_SVGS = ${literal(bodies)} as const\n\n` +
      `export type IconName = keyof typeof ICON_SVGS\n\n` +
      `/** The few icons not drawn on a 0 0 16 16 grid. */\n` +
      `export const ICON_VIEWBOXES: Partial<Record<IconName, string>> = ${literal(viewBoxes)}\n`
  )
  writeFileSync(
    join(OUT, 'associations.ts'),
    header([ICONS]) +
      `import type { IconName } from './svgs'\n\n` +
      `/** Whole file names, lower-cased. */\n` +
      `export const FILE_NAMES: Record<string, IconName> = ${literal(fileNames)}\n\n` +
      `/** Extensions without the leading dot, lower-cased; compound ones such as "test.tsx" included. */\n` +
      `export const FILE_EXTENSIONS: Record<string, IconName> = ${literal(fileExtensions)}\n`
  )
  writeFileSync(
    join(OUT, 'palette.ts'),
    header([PALETTE]) +
      `\nexport type CtpColor = ${colors.map((c) => `'${c}'`).join(' | ')}\n\n` +
      `/** Catppuccin Latte (light) and Mocha (dark), for the \`--ctp-*\` colours the icons use. */\n` +
      `export const ICON_PALETTE: Record<'latte' | 'mocha', Record<CtpColor, string>> = ${literal({ latte: pick('latte'), mocha: pick('mocha') })}\n`
  )
  execFileSync('bunx', ['oxfmt', OUT], { cwd: ROOT, stdio: 'inherit' })
  console.log(
    `${used.length} icons, ${colors.length} colours, ${Object.keys(fileNames).length} file names, ` +
      `${Object.keys(fileExtensions).length} extensions` +
      (missing.size ? `; no SVG for ${[...missing].join(', ')}` : '') +
      (languageOnly.length ? `; language id only, skipped: ${languageOnly.join(', ')}` : '')
  )
} finally {
  rmSync(work, { recursive: true, force: true })
}
